class ProductOfNumbers {
public:
    vector<int> v;
    ProductOfNumbers() {
    }
    
    void add(int num) {
        v.push_back(num);
    }
    
    int getProduct(int k) {
        int pdt = 1;
        int n = v.size();
        int cnt = 0;
        while(cnt < k){
            pdt *= v[n-1-cnt];
            cnt++;
        }
        return pdt;
    }
};

